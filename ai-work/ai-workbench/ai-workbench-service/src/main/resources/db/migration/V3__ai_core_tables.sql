-- 工作台核心表（V1 对话 / 任务 / 快照 / 报告）。不建 ai_outbox、ai_task_approval、ai_operation_record。

CREATE TABLE ai_conversation (
    id               BIGINT        NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    conversation_id  VARCHAR(64)   NOT NULL COMMENT '对外会话 ID',
    user_id          VARCHAR(64)   NOT NULL COMMENT '归属用户',
    title            VARCHAR(200)  NULL COMMENT '标题',
    created_at       DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at       DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_conversation_id (conversation_id),
    KEY idx_ai_conversation_user_updated (user_id, updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AI 会话';

CREATE TABLE ai_message (
    id               BIGINT        NOT NULL AUTO_INCREMENT,
    conversation_id  VARCHAR(64)   NOT NULL COMMENT '会话 ID',
    user_id          VARCHAR(64)   NOT NULL,
    role             VARCHAR(16)   NOT NULL COMMENT 'user/assistant/system',
    content          MEDIUMTEXT    NULL,
    task_id          VARCHAR(64)   NULL COMMENT '关联任务',
    stream_interrupted TINYINT(1)  NOT NULL DEFAULT 0,
    created_at       DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_ai_message_conversation (conversation_id, id),
    KEY idx_ai_message_task (task_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='会话消息';

CREATE TABLE ai_task (
    id                  BIGINT        NOT NULL AUTO_INCREMENT,
    task_id             VARCHAR(64)   NOT NULL,
    task_type           VARCHAR(32)   NOT NULL COMMENT 'EXPLOSION/QUALITY',
    task_status         VARCHAR(32)   NOT NULL COMMENT 'QUEUED/RUNNING/SUCCEEDED/FAILED/RETRY_WAIT/CANCELLED',
    user_id             VARCHAR(64)   NOT NULL,
    merchant_id         VARCHAR(64)   NULL,
    conversation_id     VARCHAR(64)   NULL,
    thread_id           VARCHAR(64)   NULL,
    current_run_id      VARCHAR(64)   NULL,
    lease_token         VARCHAR(64)   NULL,
    lease_owner         VARCHAR(128)  NULL,
    lease_expires_at    DATETIME(3)   NULL,
    last_heartbeat_at   DATETIME(3)   NULL,
    cancel_requested_at DATETIME(3)   NULL,
    idempotency_key     VARCHAR(128)  NULL,
    input_json          JSON          NULL COMMENT '任务输入，避免无界大数组',
    priority            INT           NOT NULL DEFAULT 0,
    available_at        DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    next_action         VARCHAR(16)   NOT NULL DEFAULT 'START' COMMENT 'START/RESUME',
    workflow_version    VARCHAR(64)   NULL,
    deadline_at         DATETIME(3)   NULL,
    scoring_version     VARCHAR(64)   NULL,
    result_json         JSON          NULL,
    error_code          VARCHAR(64)   NULL,
    error_message       VARCHAR(1000) NULL,
    attempt_count       INT           NOT NULL DEFAULT 0,
    max_attempts        INT           NOT NULL DEFAULT 3,
    version             INT           NOT NULL DEFAULT 0,
    created_at          DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at          DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    started_at          DATETIME(3)   NULL,
    finished_at         DATETIME(3)   NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_task_id (task_id),
    UNIQUE KEY uk_ai_task_idempotency (user_id, idempotency_key),
    KEY idx_ai_task_claim (task_status, task_type, priority, available_at),
    KEY idx_ai_task_conversation (conversation_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='业务任务（兼队列）';

CREATE TABLE ai_run (
    id             BIGINT        NOT NULL AUTO_INCREMENT,
    run_id         VARCHAR(64)   NOT NULL,
    task_id        VARCHAR(64)   NOT NULL,
    lease_token    VARCHAR(64)   NULL,
    run_status     VARCHAR(32)   NOT NULL COMMENT 'RUNNING/SUCCEEDED/FAILED/TIMEOUT',
    worker_id      VARCHAR(128)  NULL,
    error_code     VARCHAR(64)   NULL,
    error_message  VARCHAR(1000) NULL,
    started_at     DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    finished_at    DATETIME(3)   NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_run_id (run_id),
    KEY idx_ai_run_task (task_id, started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='任务执行尝试';

